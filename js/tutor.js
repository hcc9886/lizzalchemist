export function tutorReply(question, context) {
  const q = (question || '').toLowerCase();
  let ctxHint = '';
  if (context && context.unit) ctxHint = '\n\n（你正在学习单元「' + context.unit + '」，可以把问题问得更具体。）';
  if (context && context.exp) ctxHint = '\n\n（你刚在做实验「' + context.exp + '」，可以结合刚才的参数提问。）';
  for (const item of KB) {
    if (item.k.some(kw => q.includes(kw.toLowerCase()))) {
      return item.a + ctxHint;
    }
  }
  return FALLBACKS[Math.floor((q.length + (context ? context.length : 0)) % FALLBACKS.length)] + ctxHint;
}

